import { AGENTS_FILE, BRAIN, BRAIN_DIRS, BRAIN_LOG, ME } from '@notes/shared';

/**
 * Files a new vault starts with. Each is written only if it does not exist,
 * so your edits (including to AGENTS.md) are never overwritten.
 */
export function starterFiles(today: string): Record<string, string> {
  return {
    [AGENTS_FILE]: AGENTS_MD,
    [BRAIN_LOG]: `# Agent log\n\nAgents add one line per piece of work, newest at the bottom.\n\n- ${today} · thoughtwell · Vault created.\n`,
    [`${ME}/Welcome.md`]: WELCOME_MD,
  };
}

export const AGENTS_MD = `<!-- Thoughtwell vault instructions for AI agents, format v1. Edit freely: Thoughtwell never overwrites this file. -->
# Instructions for AI agents

This folder is a Thoughtwell vault: one person's second brain, stored as plain
Markdown files. It has two areas.

| Folder | Who writes | What it is |
| --- | --- | --- |
| \`${ME}/\` | **The owner only** | Their own notes, thoughts and ideas. |
| \`${BRAIN}/\` | **You, the agents** | Everything you ingest, summarize and organize. |

## The rules

1. **Never create, edit, move or delete anything in \`${ME}/\`.** You may read it to
   learn what the owner is interested in and working on, so your summaries and
   topics are useful to them.
2. **Never delete files.** If something is a duplicate or junk, say so in the log
   and leave it where it is.
3. Do not edit this file or anything outside \`${BRAIN}/\` unless the owner asks.
4. Keep originals. Your notes point back to them.

## Layout of \`${BRAIN}/\`

\`\`\`
${BRAIN_DIRS.inbox}/      New material to process: documents, PDFs, videos, audio, web clippings, links.
${BRAIN_DIRS.sources}/    Originals, moved here once processed. Keep the original file name.
${BRAIN_DIRS.summaries}/  One note per source: what it says and why it matters.
${BRAIN_DIRS.topics}/     Hub notes that connect ideas across many sources (people, projects, themes).
${BRAIN_LOG}       One line per piece of work, newest at the bottom.
\`\`\`

You may add subfolders inside \`Sources/\`, \`Summaries/\` and \`Topics/\` when a
group of material clearly belongs together.

## Processing the inbox

For each item in \`${BRAIN_DIRS.inbox}/\`:

1. Read it. For video or audio, make a transcript if you can and save it beside the
   original as \`<original name>.transcript.md\`. For a \`.url\` or a note that only holds
   a link, fetch the page and save a readable copy as Markdown in \`Sources/\`.
2. Move the original to \`${BRAIN_DIRS.sources}/\`. If the name is taken, add \` (2)\`, \` (3)\`…
3. Write a summary note in \`${BRAIN_DIRS.summaries}/\` named after the source's title,
   using the frontmatter below. Start with a short summary, then key points,
   notable quotes or figures, and open questions.
4. Link it into one or more topic notes in \`${BRAIN_DIRS.topics}/\`: create the topic
   if it does not exist, and add a line linking to the new summary.
5. Add a line to \`${BRAIN_LOG}\`:
   \`- YYYY-MM-DD · <your name> · Summarized [[Title]] from Sources/<file>.\`

If you cannot process something, leave it in the inbox and log why.

## Note format

Notes are GitHub-flavored Markdown with YAML frontmatter:

\`\`\`markdown
---
title: The source's title
type: summary            # summary, topic, person, project, idea, transcript
source: Brain/Sources/original-file.pdf   # vault path from the root, or a URL
tags: [learning, ai-agents]
summary: One sentence the owner can read in a list.
author: claude           # your name
created: 2026-11-19
updated: 2026-11-19
---

# The source's title

Short summary paragraph.

## Key points
- …
\`\`\`

- Link to other notes with \`[[Note name]]\` (the file name without \`.md\`).
- Link to files with relative Markdown links, for example \`[Original](../Sources/report.pdf)\`.
- Use lowercase, hyphenated tags. Reuse existing tags before inventing new ones.
- Diagrams: a \`\`\`mermaid code fence.
- Charts: a \`\`\`chart code fence holding JSON:
  \`{"type": "bar", "title": "…", "labels": ["a", "b"], "series": [{"name": "…", "values": [1, 2]}]}\`
  (\`type\` is bar, line or pie).
- Images: \`![description](attachments/name.png)\`, with the file in an \`attachments/\` folder beside the note.
- No raw HTML. Keep file names readable: the title, without dates or IDs.

When you update a note, keep the owner's or other agents' text, and update \`updated:\`.
`;

